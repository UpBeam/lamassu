import tempfile
import unittest
from pathlib import Path
from lamassu.archive import Archive
from lamassu.notes import publish_draft, render_note, write_new
from test_archive import fixture


class NoteTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.archive = Archive(self.root / "archive.sqlite")
        self.id = self.archive.ingest(fixture())["record_id"]

    def tearDown(self):
        self.archive.close()
        self.temp.cleanup()

    def test_note_preserves_roles_and_concrete_source_evidence(self):
        note_id, raw = render_note(
            self.archive,
            [self.id],
            "My interpretation",
            "An explicitly authored statement.",
        )
        text = raw.decode()
        self.assertIn("status: draft", text)
        self.assertIn("authorship: user-supplied", text)
        self.assertIn(self.id, text)
        self.assertIn("> A guardian preserves evidence.", text)
        self.assertIn("**user · m1**", text)
        self.assertIn("not been verified or generated by a model", text)
        self.assertEqual(len(note_id), 64)

    def test_create_only_publishing_never_overwrites(self):
        inbox = self.root / "inbox"
        inbox.mkdir()
        result = publish_draft(self.archive, inbox, [self.id], "A title", "A statement")
        path = Path(result["path"])
        before = path.read_bytes()
        with self.assertRaises(FileExistsError):
            publish_draft(self.archive, inbox, [self.id], "A title", "A statement")
        self.assertEqual(path.read_bytes(), before)
        self.assertEqual(path.parent, inbox)

    def test_symlink_destination_is_not_followed(self):
        target = self.root / "human.md"
        target.write_text("preserve me")
        link = self.root / "alias.md"
        link.symlink_to(target)
        with self.assertRaises(FileExistsError):
            write_new(link, b"bad")
        self.assertEqual(target.read_text(), "preserve me")
        inbox = self.root / "inbox"
        inbox.mkdir()
        alias = self.root / "inbox-alias"
        alias.symlink_to(inbox, target_is_directory=True)
        with self.assertRaises(ValueError):
            publish_draft(self.archive, alias, [self.id], "title", "text")

    def test_unsafe_metadata_stays_inert_and_title_cannot_inject_frontmatter(self):
        _, raw = render_note(
            self.archive,
            [self.id],
            "[click](https://example.invalid) <script>",
            "Human claim",
        )
        self.assertIn(r"\[click\]", raw.decode())
        self.assertIn(r"\<script\>", raw.decode())
        for ids, title in [
            ([], "title"),
            ([self.id, self.id], "title"),
            ([self.id], "title\n---\nstatus: reviewed"),
        ]:
            with self.assertRaises(ValueError):
                render_note(self.archive, ids, title, "statement")

    def test_imported_markdown_cannot_embed_active_html_or_images(self):
        raw = fixture(
            messages=[
                dict(
                    id="m1",
                    role="tool",
                    text='<img src="https://example.invalid/pixel">\n![image](https://example.invalid/pixel)\n# injected heading',
                )
            ]
        )
        record = self.archive.ingest(raw)["record_id"]
        _, note = render_note(
            self.archive, [record], "Evidence", "A user-authored interpretation"
        )
        text = note.decode()
        self.assertNotIn("> <img", text)
        self.assertNotIn("> ![", text)
        self.assertIn("> \\<img", text)
        self.assertIn("**tool · m1**", text)

    def test_failed_publication_leaves_no_partial_note_or_temporary_file(self):
        from unittest.mock import patch

        destination = self.root / "never-created.md"
        with patch("lamassu.notes.os.link", side_effect=OSError("synthetic failure")):
            with self.assertRaises(OSError):
                write_new(destination, b"complete contents")
        self.assertFalse(destination.exists())
        self.assertEqual(list(self.root.glob(".lamassu-*")), [])

    def test_new_cli_files_have_private_permissions_on_posix(self):
        import os
        import stat

        if os.name != "posix":
            self.skipTest("POSIX file modes only")
        destination = self.root / "private.md"
        write_new(destination, b"evidence")
        self.assertEqual(stat.S_IMODE(destination.stat().st_mode), 0o600)
        self.assertEqual(
            stat.S_IMODE((self.root / "archive.sqlite").stat().st_mode), 0o600
        )
