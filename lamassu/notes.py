"""Create-only, explicitly authored evidence notes. No automated synthesis."""

import hashlib
import json
import os
import re
import tempfile
from pathlib import Path
from .archive import _text


def _escape(text):
    return re.sub(r"([\\`*_{}\[\]<>#!|])", r"\\\1", text)


def _inline(text):
    """Keep untrusted metadata on one inert Markdown line."""
    return _escape(" ".join(text.split()))


def render_note(archive, record_ids, title, statement):
    _text(title, 160)
    _text(statement, 12000)
    if "\n" in title or "\r" in title:
        raise ValueError("title must be one line")
    if (
        not record_ids
        or len(record_ids) > 10
        or len(set(record_ids)) != len(record_ids)
    ):
        raise ValueError("select 1 to 10 distinct source revisions")
    records = [archive.get(record_id) for record_id in record_ids]
    key = json.dumps([title, statement, record_ids])
    note_id = hashlib.sha256(key.encode()).hexdigest()
    lines = [
        "---",
        "type: lamassu-evidence-note",
        "status: draft",
        "authorship: user-supplied",
        "review_required: true",
        f"note_id: {note_id}",
        "sources:",
    ]
    lines.extend(f'  - "{r["record_id"]}"' for r in records)
    lines.extend(
        [
            "---",
            "",
            f"# {_inline(title)}",
            "",
            "## Proposed understanding",
            "",
            statement,
            "",
            "> Draft: this statement was explicitly supplied by the author. It has not been verified or generated by a model.",
            "",
            "## Evidence",
        ]
    )
    for record in records:
        lines.extend(
            [
                "",
                f"### {_inline(record['provider'])} / {_inline(record['external_id'])}",
                "",
                f"- Source revision: `{record['record_id']}`",
                f"- Original bytes SHA-256: `{record['digest']}`",
                "",
            ]
        )
        # Exact text stays quoted, role-labeled, and separate from the supplied statement.
        for message in record["messages"]:
            lines.extend(
                [
                    f"**{_inline(message['role'])} · {_inline(message['message_id'])}**",
                    "",
                ]
            )
            for line in message["text"].splitlines() or [""]:
                lines.append("> " + _escape(line))
            lines.append("")
    lines.extend(
        [
            "## Review",
            "",
            "- [ ] Check that the proposed understanding follows from the evidence.",
            "- [ ] Resolve contradictions and check whether the information is current.",
            "- [ ] Move the useful synthesis into the appropriate curated note.",
            "",
        ]
    )
    raw = "\n".join(lines).encode("utf-8")
    if len(raw) > 512 * 1024:
        raise ValueError("evidence note exceeds 512 KiB; select smaller source records")
    return note_id, raw


def write_new(path, raw):
    """Publish a complete file atomically, without replacing an existing entry.

    Requires a filesystem supporting hard links; the parent is owner-controlled.
    """
    path = Path(path)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix=".lamassu-", dir=path.parent, delete=False
        ) as target:
            temporary = Path(target.name)
            target.write(raw)
            target.flush()
            os.fsync(target.fileno())
        # The temporary file lives on the same filesystem. link() fails if ANY
        # destination entry already exists, including a symlink. No partial
        # final file is visible if writing the temporary file fails.
        os.link(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return path


def publish_draft(archive, inbox, record_ids, title, statement):
    inbox = Path(inbox)
    if not inbox.is_dir() or inbox.is_symlink():
        raise ValueError("inbox must be an existing directory, not a symlink")
    note_id, raw = render_note(archive, record_ids, title, statement)
    # Destination names are generated, not accepted from imported text.
    path = inbox / f"lamassu-{note_id[:20]}.md"
    write_new(path, raw)
    return dict(path=str(path), note_id=note_id, bytes=len(raw), status="draft")
